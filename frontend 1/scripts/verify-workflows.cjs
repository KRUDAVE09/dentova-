require('dotenv').config({ quiet: true });
const { chromium } = require('playwright');
const fs = require('node:fs');
const { db, pool } = require('../src/db/index.ts');
const schema = require('../src/db/schema.ts');
const { eq, notInArray, gt } = require('drizzle-orm');
const base = process.env.QA_BASE_URL || 'http://127.0.0.1:3000';
const assert = (value, message) => { if (!value) throw new Error(message); console.log('PASS', message); };
const getData = async () => (await fetch(base + '/api/clinic')).json();

(async () => {
 const baseline = await getData();
 let browser;
 let failed = false;
 const errors = [];
 fs.mkdirSync('artifacts', { recursive: true });
 try {
  browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base, { waitUntil: 'networkidle' });
  if (process.env.QA_LATEST_STYLES) await page.addStyleTag({ content: fs.readFileSync('src/app/globals.css', 'utf8').replace('@import "tailwindcss";', '') });
  await page.screenshot({ path: 'artifacts/dentflow-desktop.png', fullPage: true });
  assert(await page.locator('.chair-card').count() === 3, 'Three-chair layout renders');
  assert(await page.locator('.queue-table tbody tr').count() === 5, 'Shared waiting queue renders five patients');
  assert(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth), 'Desktop has no horizontal overflow');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'artifacts/dentflow-mobile.png', fullPage: true });
  assert(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth), 'Mobile has no horizontal overflow');
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
  await page.locator('.nav-item').filter({ hasText: /^Patients$/ }).click();
  assert(await page.locator('h1').innerText() === 'Patients', 'Mobile navigation works');
  await page.setViewportSize({ width: 1440, height: 1000 });
  const go = async name => { await page.locator('.nav-item').filter({ hasText: new RegExp('^' + name + '(\\d+)?$') }).click(); await page.waitForTimeout(120); };
  const save = async locator => {
   const result = page.waitForResponse(r => r.url().endsWith('/api/clinic') && r.request().method() === 'POST');
   await locator.click();
   const response = await result;
   if (!response.ok()) throw new Error('Mutation failed: ' + await response.text());
   await page.getByRole('dialog').waitFor({ state: 'hidden' });
  };
  await go('Waiting room');
  await page.getByRole('button', { name: /Walk-ins/ }).click();
  assert(await page.locator('.queue-table tbody tr').count() === 1, 'Walk-in queue filter works');
  await page.getByRole('button', { name: /All patients/ }).click();
  await page.getByRole('button', { name: 'Call next patient', exact: true }).click();
  await save(page.getByRole('dialog').getByRole('button', { name: 'Call & assign patient', exact: true }));
  assert(await page.locator('.queue-table tbody tr').count() === 4, 'Assignment removes the next patient from queue');
  let chairTwo = page.locator('.chair-card').filter({ has: page.getByRole('heading', { name: 'Chair 02', exact: true }) });
  assert((await chairTwo.innerText()).includes('Emma Thompson'), 'Assigned patient appears on Chair 02');
  await chairTwo.getByRole('button', { name: 'View details', exact: true }).click();
  await save(page.getByRole('dialog').getByRole('button', { name: 'Complete treatment', exact: true }));
  assert((await chairTwo.innerText()).includes('Cleaning'), 'Completed treatment moves chair to Cleaning');
  await chairTwo.getByRole('button', { name: 'Mark as ready', exact: true }).click();
  await page.waitForFunction(() => [...document.querySelectorAll('.chair-card')].some(c => c.textContent.includes('Chair 02') && c.textContent.includes('Available')));
  assert(true, 'Cleaned chair can be marked Available');
  const blocked = await page.request.post(base + '/api/clinic', { data: { action: 'settings', chairCount: 1 } });
  assert(blocked.status() === 400, 'Occupied chairs cannot be removed');
  const overlap = await page.request.post(base + '/api/clinic', { data: { action: 'appointment', patientId: baseline.patients[0].id, date: baseline.visits[0].date, time: '10:00', doctor: 'Dr. Sarah Miller', treatment: 'Routine check-up' } });
  assert(overlap.status() === 400, 'Overlapping dentist appointments are rejected');
  await go('Patients');
  await page.getByRole('button', { name: 'Add patient', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.locator('input[name="name"]').fill('QA Jamie Rivera');
  await dialog.locator('input[name="age"]').fill('29');
  await dialog.locator('input[name="email"]').fill('qa.jamie@example.com');
  await save(dialog.getByRole('button', { name: 'Add patient', exact: true }));
  let data = await getData();
  const patient = data.patients.find(p => p.name === 'QA Jamie Rivera');
  assert(Boolean(patient), 'New patient is persisted in PostgreSQL');
  await go('Appointments');
  await page.getByRole('button', { name: 'New appointment', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.locator('select[name="patientId"]').selectOption(String(patient.id));
  const future = new Date(); future.setDate(future.getDate() + 2);
  const futureDate = `${future.getFullYear()}-${String(future.getMonth() + 1).padStart(2, '0')}-${String(future.getDate()).padStart(2, '0')}`;
  await dialog.locator('input[name="date"]').fill(futureDate);
  await dialog.locator('input[name="time"]').fill('16:00');
  await save(dialog.getByRole('button', { name: 'Book appointment', exact: true }));
  data = await getData();
  assert(data.visits.some(v => v.patientId === patient.id && v.date === futureDate && v.status === 'upcoming'), 'Booking creates a dated appointment');
  await go('Waiting room');
  await page.getByRole('button', { name: 'Check in patient', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.locator('select[name="patientId"]').selectOption(String(patient.id));
  await dialog.locator('select[name="kind"]').selectOption('walk-in');
  await save(dialog.getByRole('button', { name: 'Check in patient', exact: true }));
  data = await getData();
  const checkIn = data.visits.find(v => v.patientId === patient.id && v.status === 'waiting');
  assert(Boolean(checkIn), 'Patient check-in creates a waiting visit');
  const duplicate = await page.request.post(base + '/api/clinic', { data: { action: 'check-in', patientId: patient.id } });
  assert(duplicate.status() === 400, 'Duplicate patient check-in is rejected');
  await page.keyboard.press('Control+k');
  await page.getByRole('textbox', { name: 'Search the clinic' }).fill('Emma Thompson');
  await page.getByRole('dialog').getByRole('button', { name: /Emma Thompson/ }).click();
  assert(await page.getByRole('dialog').getByRole('heading', { name: 'Emma Thompson', exact: true }).count() === 1, 'Global search opens the patient record');
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert(true, 'Escape closes accessible dialogs');
  await go('Billing');
  await page.getByRole('button', { name: 'Record payment', exact: true }).first().click();
  await save(page.getByRole('dialog').getByRole('button', { name: 'Record payment', exact: true }));
  assert((await getData()).visits.filter(v => v.paymentStatus === 'paid').length > baseline.visits.filter(v => v.paymentStatus === 'paid').length, 'Offline payment recording persists');
  await go('Inventory');
  await page.locator('tbody tr').filter({ hasText: 'Nitrile examination gloves' }).getByRole('button', { name: 'Update stock' }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('spinbutton').fill('42');
  await save(dialog.getByRole('button', { name: 'Update stock', exact: true }));
  assert((await getData()).inventory.find(i => i.name === 'Nitrile examination gloves').quantity === 42, 'Inventory stock update persists');
  await go('Messages');
  await page.getByRole('textbox', { name: 'Your message' }).fill('QA: Looking forward to your next smile.');
  const sendResponse = page.waitForResponse(r => r.url().endsWith('/api/clinic') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await sendResponse;
  await page.getByText('QA: Looking forward to your next smile.', { exact: true }).waitFor();
  assert(true, 'Conversation messages are saved and rendered');
  await go('Reports');
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export report', exact: true }).click();
  const download = await downloadEvent;
  assert(download.suggestedFilename().endsWith('.csv'), 'Reports export a real CSV file');
  for (const section of ['Overview', 'Treatments', 'Follow-ups', 'Settings']) {
   await go(section);
   assert((await page.locator('main').innerText()).length > 200, `${section} screen renders meaningful content`);
  }
  await go('Waiting room');
  for (const count of [5, 10, 3]) {
   await page.getByRole('button', { name: 'Manage chairs', exact: true }).click();
   dialog = page.getByRole('dialog');
   await dialog.getByRole('spinbutton', { name: 'Chair count' }).fill(String(count));
   await save(dialog.getByRole('button', { name: 'Save chair setup', exact: true }));
   assert(await page.locator('.chair-card').count() === count, `${count}-chair layout persists and renders`);
   if (count === 10) await page.screenshot({ path: 'artifacts/dentflow-ten-chairs.png', fullPage: true });
  }
  data = await getData();
  const available = data.chairs.find(c => c.status === 'available');
  const next = data.visits.find(v => v.status === 'waiting');
  const concurrent = await Promise.all([1, 2].map(() => page.request.post(base + '/api/clinic', { data: { action: 'assign', chairId: available.id, visitId: next.id } })));
  assert(concurrent.filter(r => r.ok()).length === 1, 'Concurrent assignment allows only one successful transaction');
  data = await getData();
  for (const chair of data.chairs.filter(c => c.status === 'in_treatment')) await page.request.post(base + '/api/clinic', { data: { action: 'complete', chairId: chair.id } });
  data = await getData();
  for (const chair of data.chairs.filter(c => c.status === 'cleaning')) await page.request.post(base + '/api/clinic', { data: { action: 'ready', chairId: chair.id } });
  const single = await page.request.post(base + '/api/clinic', { data: { action: 'settings', chairCount: 1 } });
  assert(single.ok(), 'A ready clinic can scale down to one chair');
  await page.getByRole('button', { name: 'Refresh waiting room', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.chair-card').length === 1);
  const cardWidth = (await page.locator('.chair-card').boundingBox()).width;
  const gridWidth = (await page.locator('.chairs-grid').boundingBox()).width;
  assert(cardWidth < gridWidth / 2, 'One-chair layout keeps a compact readable card');
  assert(errors.length === 0, 'No browser runtime errors during all workflows');
  console.log('ALL WORKFLOW CHECKS PASSED');
 } catch (error) {
  failed = true; console.error('WORKFLOW CHECK FAILED:', error);
 } finally {
  if (browser) await browser.close();
  await db.transaction(async tx => {
   await tx.delete(schema.chairs);
   await tx.delete(schema.messages).where(notInArray(schema.messages.id, baseline.messages.map(m => m.id)));
   await tx.delete(schema.visits).where(notInArray(schema.visits.id, baseline.visits.map(v => v.id)));
   await tx.delete(schema.patients).where(notInArray(schema.patients.id, baseline.patients.map(p => p.id)));
   for (const patient of baseline.patients) await tx.update(schema.patients).set(patient).where(eq(schema.patients.id, patient.id));
   const waiting = baseline.visits.filter(v => v.status === 'waiting').sort((a,b) => new Date(a.checkedInAt) - new Date(b.checkedInAt));
   for (const visit of baseline.visits) {
    const index = waiting.findIndex(v => v.id === visit.id);
    const checkedInAt = index >= 0 ? new Date(Date.now() - [12,9,8,6,5][index] * 60000).toISOString() : visit.checkedInAt;
    await tx.update(schema.visits).set({ ...visit, checkedInAt }).where(eq(schema.visits.id, visit.id));
   }
   await tx.insert(schema.chairs).values(baseline.chairs.map((chair, i) => ({ ...chair, startedAt: chair.startedAt ? new Date(Date.now() - (i === 0 ? 18 : 12) * 60000).toISOString() : null })));
   for (const item of baseline.inventory) await tx.update(schema.inventory).set(item).where(eq(schema.inventory.id, item.id));
   for (const message of baseline.messages) await tx.update(schema.messages).set(message).where(eq(schema.messages.id, message.id));
   await tx.update(schema.clinicSettings).set(baseline.settings).where(eq(schema.clinicSettings.id, 1));
   await tx.delete(schema.activity).where(gt(schema.activity.id, Math.max(0, ...baseline.activity.map(a => a.id))));
  });
  await pool.end();
  console.log('Original fictional clinic restored.');
  if (failed) process.exitCode = 1;
 }
})();
